// Token Radar — model radar-2.
//
// One sealed DefiLlama snapshot in, one ranked board out. The board ranks only
// protocols that *record no token* and are not a wrapped, staked or bridged
// product of a token that already trades: the same exclusion rule the snapshot's
// own watchlist uses, applied to every candidate, not just the watchlist. A
// protocol whose token already trades is never ranked; it is shown separately,
// at the market's own value, in the dashboard's Live view. A pre-token protocol
// that is a wrapped/staked/bridge product is likewise set aside, with its reason,
// in the dashboard's Set-aside view.
//
// Implied value uses only the snapshot's own figures — never a name:
//
//   base      = tvl_usd x base_multiple
//   growth    = clamp(change_7d, growth_floor, growth_cap)   (per cent)
//   growthMul = 1 + (growth / 100) x growth_weight
//   maturity  = maturity_floor + min(age_days, maturity_days) / maturity_days
//               x maturity_range            (age unknown: unknown_age_days)
//   chainMul  = 1 + min(max(chains - 1, 0), chain_max_extra) x chain_step
//   implied   = max(1, round(base x growthMul x maturity x chainMul))
//
// TVL is the size of the launch, 7-day growth is its momentum, age with no
// token is how long the launch has been waited for, and the chain count is a
// small diversification term (a protocol live on several chains is less exposed
// to one chain's fate). Nothing in the formula names a protocol.

export interface SnapshotProtocol {
  slug: string;
  name: string;
  category: string | null;
  chains: string[];
  tvl_usd: number;
  change_7d: number | null;
  mcap_usd: number | null;
  listed_at: string | null;
  gecko_id: string | null;
  symbol: string | null;
}

export interface Snapshot {
  as_of: string;
  source: string;
  floor_usd: number;
  protocols: SnapshotProtocol[];
  watchlist: string[];
}

export interface ModelConstants {
  base_multiple: number;
  growth_weight: number;
  growth_floor: number;
  growth_cap: number;
  maturity_floor: number;
  maturity_range: number;
  maturity_days: number;
  unknown_age_days: number;
  chain_step: number;
  chain_max_extra: number;
}

export const MODEL: ModelConstants = {
  base_multiple: 0.22,
  growth_weight: 0.6,
  growth_floor: -50,
  growth_cap: 150,
  maturity_floor: 0.55,
  maturity_range: 0.45,
  maturity_days: 1460,
  unknown_age_days: 365,
  chain_step: 0.03,
  chain_max_extra: 4,
};

export const MODEL_VERSION = 'radar-2';

/** How many live-token protocols the dashboard's Live view carries, by market cap. */
export const LIVE_ROWS = 24;

